"""
Defines the VerificationEngine interface which is used to verify the fairness
of the values (rolls, numbers, etc.) generated by the RandomnessEngine.
"""

from abc import ABC, abstractmethod

from src.utils.types import ValueRecord, VerificationResult


class VerificationEngine(ABC):
    """
    Defines all the operations needed to verify the fairness of the generated
    values (rolls, numbers, etc.).
    """

    @abstractmethod
    def verify(
        self, record: ValueRecord, disclosed_server_seed: str
    ) -> VerificationResult:
        """
        Simulates the verification process a user would undertake to verify if
        the outcome of pfd is fair.
        """
        raise NotImplementedError()

    @abstractmethod
    def safe_compare(self, a: bytes, b: bytes) -> bool:
        """
        Compares two byte strings in such a way that is resistant to timing
        attacks.
        """
        raise NotImplementedError()
